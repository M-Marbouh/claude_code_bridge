# Local ids keep the existing fork form generated by ``ccb_protocol.make_req_id``
# (lib/ccb_protocol.py:47-56) and accepted by ``bin/pend`` TASK_ID_RE
# (bin/pend:57): ``YYYYMMDD-HHMMSS-mmm-PID-counter``, where the counter is
# optional. Remote ids are ``<local-id>-h<issuer-host-token>``.
LOCAL_ID_PATTERN = r"\d{8}-\d{6}-\d{3}-\d+(?:-\d+)?"
HOST_TOKEN_PATTERN = r"[a-z0-9]{4,32}"
REMOTE_ID_SEPARATOR = "-h"

_LOCAL_ID_RE = re.compile(LOCAL_ID_PATTERN)
_HOST_TOKEN_RE = re.compile(HOST_TOKEN_PATTERN)

# Submit record schema. Version 1 is delivery-only (M1, unchanged); version 2
# is the same record with ``reply_expected=true`` and nothing else different.
SCHEMA_VERSION = 1
SCHEMA_VERSION_REPLY = 2

#: Remote delivery is advertised only for providers whose delivery path is
#: proven. Claude and Codex use the existing delivery-only peer path.
REMOTE_PROVIDERS = ("claude", "codex")

#: No ask-side message cap exists in this fork: ``bin/ask``,
#: ``bin/ccb-bridge-ask`` and ``lib/ccb_protocol.py`` accept the peer text
#: unvalidated, and the plan (section 7) says the message cap "reuses current
#: ask limit". There is nothing to reuse, so M1 fixes a provisional 64 KiB cap
#: here, well inside MAX_FRAME. Raise it deliberately, with a protocol bump.
MAX_TEXT_BYTES = 64 * 1024
MAX_INTENT_CHARS = 1024
MAX_SESSION_ID_LENGTH = 256

#: The alias is resolved and authorized on the destination (T2); this build
#: only bounds its shape, so a path or shell metacharacter can never travel.
_PROJECT_ALIAS_RE = re.compile(r"[A-Za-z0-9][A-Za-z0-9._-]{0,63}")
_DIGEST_RE = re.compile(r"[0-9a-f]{64}")

REQUEST_FIELDS = frozenset(
    {
        "schema_version",
        "dest_project",
        "dest_provider",
        "dest_session",
        "text",
        "reply_expected",
        "intent",
        "source_claims",
        "request_id",
        "digest",
    }
)

#: Fields covered by the payload digest. ``source_claims`` is audit-only and
#: ``op_id`` belongs to the transport, so neither is covered.
DIGEST_FIELDS = (
    "schema_version",
    "dest_project",
    "dest_provider",
    "dest_session",
    "text",
    "reply_expected",
    "intent",
    "request_id",
)


class ProtocolError(ValueError):
    """A refusal carrying one of the enumerated ``ERR_*`` codes."""

    def __init__(self, code: str, message: str):
        super().__init__(message)
        self.code = code
        self.message = message


# --------------------------------------------------------------------------- #
# Framing
# --------------------------------------------------------------------------- #


def _reject_duplicate_keys(pairs: list[tuple[str, object]]) -> dict:
    result: dict = {}
    for key, value in pairs:
        if key in result:
            # Deliberately not echoed: the key is sender-controlled content.
            raise ProtocolError(ERR_DUPLICATE_KEY, "duplicate key in a JSON object")
        result[key] = value
    return result


def _reject_json_constant(name: str) -> object:
    """Refuse ``NaN`` / ``Infinity`` / ``-Infinity``: they are not JSON.

    Python's default parser accepts them, which would let a record in that can
    never be re-encoded (``allow_nan=False``) and would also smuggle
    non-finite numbers past the schema.
    """
    raise ProtocolError(ERR_INVALID_JSON, "frame body uses a non-standard JSON constant")


def _has_non_finite(value: object) -> bool:
    """True when the parsed tree holds ``inf``/``-inf``/``nan`` somewhere.

    ``parse_constant`` already refuses the ``NaN``/``Infinity`` literals, but a
    standard literal such as ``1e400`` also overflows to infinity. Refusing it
    here keeps the invariant the gate relies on: anything accepted can be
    re-encoded (``allow_nan=False``) later. Iterative, so nesting depth cannot
    turn this into a recursion error.
    """
    stack: list[object] = [value]
    while stack:
        item = stack.pop()
        if isinstance(item, float):
            if not math.isfinite(item):
                return True
        elif isinstance(item, dict):
            stack.extend(item.values())
        elif isinstance(item, list):
            stack.extend(item)
    return False


def _read_exact(stream, size: int) -> bytes:
    chunks: list[bytes] = []
    remaining = size
    while remaining > 0:
        chunk = stream.read(remaining)
        if not chunk:
            break
        chunks.append(chunk)
        remaining -= len(chunk)
    return b"".join(chunks)


def read_frame(stream) -> dict | None:
    """Read one frame from ``stream``; ``None`` on a clean EOF.

    Raises :class:`ProtocolError` for a short read, zero or oversized length,
    invalid UTF-8, invalid JSON, duplicate keys, or a non-object body.
    """
    header = _read_exact(stream, HEADER_SIZE)
    if not header:
        return None
    if len(header) != HEADER_SIZE:
        raise ProtocolError(ERR_MALFORMED_FRAME, "truncated length prefix")
    (length,) = struct.unpack(">I", header)
    if length == 0:
        raise ProtocolError(ERR_EMPTY_FRAME, "frame length must be non-zero")
    if length > MAX_FRAME:
        raise ProtocolError(
            ERR_FRAME_TOO_LARGE, f"frame length exceeds the {MAX_FRAME}-byte limit"
        )
    payload = _read_exact(stream, length)
    if len(payload) != length:
        raise ProtocolError(ERR_MALFORMED_FRAME, "truncated frame body")
    try:
        text = payload.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise ProtocolError(ERR_INVALID_UTF8, "frame body is not valid UTF-8") from exc
    try:
        value = json.loads(
            text,
            object_pairs_hook=_reject_duplicate_keys,
            parse_constant=_reject_json_constant,
        )
    except ProtocolError:
        raise
    except RecursionError as exc:
        # Deeply nested JSON must be a refusal, never an escaping traceback.
        raise ProtocolError(ERR_INVALID_JSON, "frame body is nested too deeply") from exc
    except json.JSONDecodeError as exc:
        raise ProtocolError(ERR_INVALID_JSON, f"frame body is not valid JSON: {exc.msg}") from exc
    if not isinstance(value, dict):
        raise ProtocolError(ERR_NOT_OBJECT, "frame body must be a JSON object")
    if _has_non_finite(value):
        raise ProtocolError(ERR_INVALID_JSON, "frame body contains a non-finite number")
    return value


def encode_frame(value: dict) -> bytes:
    """Serialise one frame (length prefix + UTF-8 JSON object)."""
    if not isinstance(value, dict):
        raise ProtocolError(ERR_NOT_OBJECT, "frame body must be a JSON object")
    try:
        payload = json.dumps(
            value, ensure_ascii=False, separators=(",", ":"), allow_nan=False
        ).encode("utf-8")
    except (TypeError, ValueError) as exc:
        raise ProtocolError(ERR_FRAME_ENCODE, "frame body is not JSON-serialisable") from exc
    if len(payload) > MAX_FRAME:
        raise ProtocolError(
            ERR_FRAME_TOO_LARGE, f"frame length exceeds the {MAX_FRAME}-byte limit"
        )
    return struct.pack(">I", len(payload)) + payload


def write_frame(stream, value: dict) -> None:
    """Write one frame and flush, so the peer sees it before the next read."""
    stream.write(encode_frame(value))
    flush = getattr(stream, "flush", None)
    if callable(flush):
        flush()



# Envelope validation
# --------------------------------------------------------------------------- #


def _validate_proto(value: object) -> None:
    if not isinstance(value, dict):
        raise ProtocolError(ERR_PROTOCOL_VERSION, "proto must be an object {major, minor}")
    for name in ("major", "minor"):
        field = value.get(name)
        if isinstance(field, bool) or not isinstance(field, int):
            raise ProtocolError(ERR_PROTOCOL_VERSION, f"proto {name} must be an integer")
    major = value["major"]
    minor = value["minor"]
    if major != PROTO_MAJOR:
        raise ProtocolError(
            ERR_PROTOCOL_VERSION, f"unsupported protocol major version: this build requires {PROTO_MAJOR}"
        )
    if minor < 0:
        raise ProtocolError(ERR_PROTOCOL_VERSION, "proto minor must be non-negative")
    # A higher minor is accepted: unknown non-mandatory fields and unknown
    # operations are refused or ignored per verb, never guessed at.


def validate_envelope(envelope: dict) -> dict:
    """Validate an envelope and return it unchanged.

    Unknown non-mandatory fields are ignored; a field named in ``mandatory``
    that this build does not understand is refused.
    """
    if not isinstance(envelope, dict):
        raise ProtocolError(ERR_NOT_OBJECT, "frame body must be a JSON object")
    _validate_proto(envelope.get("proto"))

    op = envelope.get("op")
    if not isinstance(op, str) or op not in VERBS:
        raise ProtocolError(ERR_UNKNOWN_OP, "unknown or missing op")

    op_id = envelope.get("op_id")
    if not isinstance(op_id, str) or not op_id or len(op_id) > MAX_OP_ID_LENGTH:
        raise ProtocolError(ERR_INVALID_REQUEST, "op_id must be a non-empty bounded string")

    mandatory = envelope.get("mandatory")
    if mandatory is not None:
        if not isinstance(mandatory, list):
            raise ProtocolError(ERR_INVALID_REQUEST, "mandatory must be a list of field names")
        for name in mandatory:
            if not isinstance(name, str) or not name:
                raise ProtocolError(
                    ERR_INVALID_REQUEST, "mandatory entries must be non-empty strings"
                )
            if name not in KNOWN_ENVELOPE_FIELDS:
                raise ProtocolError(
                    ERR_UNKNOWN_MANDATORY_FIELD, "mandatory field not understood by this build"
                )

    # `body` is required and must be a JSON object. Missing or null is refused:
    # an absent body would otherwise be silently treated as EMPTY, which turns
    # a malformed or truncated request into an accepted one.
    if "body" not in envelope or not isinstance(envelope["body"], dict):
        raise ProtocolError(ERR_INVALID_REQUEST, "body must be a JSON object")
    return envelope


def capabilities() -> dict:
    """The ``hello`` capabilities this build advertises.

    ``delivery-only`` stays advertised for Claude and Codex, so a shipped M1
    source still negotiates exactly what it asked for; ``explicit-reply`` and
    the ``fetch`` verb are additive.
    """
    return {
        "verbs": list(VERBS),
        "reply_modes": {
            provider: [DELIVERY_ONLY_MODE, EXPLICIT_REPLY_MODE]
            for provider in REMOTE_PROVIDERS
        },
        "max_frame": MAX_FRAME,
        "proto": {"major": PROTO_MAJOR, "minor": PROTO_MINOR},
    }


def reply_modes_for(capabilities: dict, provider: str) -> tuple[str, ...]:
    """The reply modes a peer advertised for ``provider`` (empty if none)."""
    modes = capabilities.get("reply_modes") if isinstance(capabilities, dict) else None
    advertised = modes.get(provider) if isinstance(modes, dict) else None
    if not isinstance(advertised, list):
        return ()
    return tuple(mode for mode in advertised if isinstance(mode, str))


def advertises(capabilities: dict, provider: str, mode: str) -> bool:
    """Capability, not protocol version, decides what a peer may be sent."""
    return mode in reply_modes_for(capabilities, provider)


def hello_response(op_id: str) -> dict:
    return {"ok": True, "op": "hello", "op_id": op_id, "capabilities": capabilities()}


def error_frame(
    code: str, message: str, *, op_id: str | None = None, op: str | None = None
) -> dict:
    """A structured refusal: ``{"ok": false, "error": {"code", "message"}}``."""
    if code not in ERROR_CODES:
        raise ProtocolError(ERR_INVALID_REQUEST, "unlisted error code")
    frame: dict = {"ok": False, "error": {"code": code, "message": message}}
    if op is not None:
        frame["op"] = op
    if op_id is not None:
        frame["op_id"] = op_id
    return frame


# --------------------------------------------------------------------------- #
# Host-qualified request ids
# --------------------------------------------------------------------------- #


def make_remote_id(local_id: str, token: str) -> str:
    """``<local-id>-h<token>``; both halves are validated, never repaired."""
    if not isinstance(local_id, str) or not _LOCAL_ID_RE.fullmatch(local_id):
        raise ProtocolError(ERR_INVALID_REQUEST, "local id does not match the local id form")
    if not isinstance(token, str) or not _HOST_TOKEN_RE.fullmatch(token):
        raise ProtocolError(
            ERR_INVALID_REQUEST, "host token must be 4-32 lowercase ASCII letters or digits"
        )
    return f"{local_id}{REMOTE_ID_SEPARATOR}{token}"


def parse_remote_id(value: str) -> tuple[str, str]:
    """Strictly parse ``<local-id>-h<token>``; split on the LAST ``-h``."""
    if not isinstance(value, str):
        raise ProtocolError(ERR_INVALID_REQUEST, "request id must be a string")
    local, separator, token = value.rpartition(REMOTE_ID_SEPARATOR)
    if not separator:
        raise ProtocolError(
            ERR_INVALID_REQUEST, "request id is not host-qualified (expected <local-id>-h<token>)"
        )
    if not _LOCAL_ID_RE.fullmatch(local) or not _HOST_TOKEN_RE.fullmatch(token):
        raise ProtocolError(ERR_INVALID_REQUEST, "request id is not host-qualified or is malformed")
    return local, token



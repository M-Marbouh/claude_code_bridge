# Submit record schema
# --------------------------------------------------------------------------- #


def canonical_json(value: object) -> str:
    """Sorted keys, no whitespace, UTF-8 preserved (``ensure_ascii=False``)."""
    return json.dumps(
        value, sort_keys=True, separators=(",", ":"), ensure_ascii=False, allow_nan=False
    )


def digest_payload(record: dict) -> dict:
    """The fields the digest covers; absent/null optional fields drop out."""
    return {name: record[name] for name in DIGEST_FIELDS if record.get(name) is not None}


def compute_digest(record: dict) -> str:
    """SHA-256 hex over the canonical JSON of the payload fields."""
    payload = canonical_json(digest_payload(record))
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


def verify_digest(record: dict) -> None:
    expected = record.get("digest")
    if not isinstance(expected, str) or not _DIGEST_RE.fullmatch(expected):
        raise ProtocolError(ERR_INVALID_REQUEST, "record digest is missing or malformed")
    if compute_digest(record) != expected:
        raise ProtocolError(ERR_DIGEST_MISMATCH, "record digest does not match its payload")


def _is_printable_ascii(value: str) -> bool:
    return all(0x20 <= ord(char) <= 0x7E for char in value)


def validate_request_record(record: dict) -> dict:
    """Validate a ``submit`` body and return it normalised.

    Any schema version other than exactly 2 goes through the unchanged M1
    path, so a v1 record (or an unsupported/wrongly-typed version) is judged
    by byte-for-byte the same rules, codes and normalisation as shipped.
    """
    schema_version = record.get("schema_version") if isinstance(record, dict) else None
    if isinstance(schema_version, bool) or schema_version != SCHEMA_VERSION_REPLY:
        return _validate_v1(record)
    return _validate_v2(record)


def _validate_v2(record: dict) -> dict:
    """Validate a schema v2 record: a v1 record that asks for one reply.

    Every other field is validated and normalised by the v1 path itself; the
    only difference allowed is ``reply_expected=true``. A v2 record that does
    not ask for a reply is refused, because one schema must have one meaning
    (delivery-only records stay v1).
    """
    reply_expected = record.get("reply_expected")
    if reply_expected is not True:
        if reply_expected is False:
            raise ProtocolError(
                ERR_INVALID_REQUEST,
                "schema v2 means reply_expected=true; use schema 1 for delivery-only",
            )
        raise ProtocolError(ERR_INVALID_REQUEST, "reply_expected must be a boolean")
    # The v1 path refuses reply_expected=true by design, so probe with the flag
    # cleared and the v1 schema number: all other checks stay exactly as M1.
    probe = dict(record)
    probe["schema_version"] = SCHEMA_VERSION
    probe["reply_expected"] = False
    normalised = _validate_v1(probe)
    normalised["schema_version"] = SCHEMA_VERSION_REPLY
    normalised["reply_expected"] = True
    return normalised


def _validate_v1(record: dict) -> dict:
    """Validate a ``submit`` body and return it normalised.

    Refuses unknown fields, a wrong schema version, an unknown/invalid
    destination, ``reply_expected=true`` (refused before acceptance, A4), and
    text beyond the message cap.
    """
    if not isinstance(record, dict):
        raise ProtocolError(ERR_INVALID_REQUEST, "request record must be a JSON object")

    unknown = set(record) - REQUEST_FIELDS
    if unknown:
        raise ProtocolError(ERR_INVALID_REQUEST, "request record has an unknown field")

    schema_version = record.get("schema_version")
    if isinstance(schema_version, bool) or schema_version != SCHEMA_VERSION:
        raise ProtocolError(
            ERR_UNSUPPORTED_SCHEMA, f"unsupported schema_version: this build accepts {SCHEMA_VERSION}"
        )

    project = record.get("dest_project")
    if not isinstance(project, str) or not _PROJECT_ALIAS_RE.fullmatch(project):
        raise ProtocolError(
            ERR_INVALID_REQUEST,
            "dest_project must be a destination alias (letters, digits, dot, underscore, hyphen)",
        )

    provider = record.get("dest_provider")
    if provider not in REMOTE_PROVIDERS:
        raise ProtocolError(
            ERR_UNSUPPORTED_PROVIDER,
            "dest_provider is not supported for remote delivery (claude, codex only)",
        )

    session = record.get("dest_session")
    if session is not None:
        if (
            not isinstance(session, str)
            or not session
            or len(session) > MAX_SESSION_ID_LENGTH
            or not _is_printable_ascii(session)
        ):
            raise ProtocolError(ERR_INVALID_REQUEST, "dest_session must be a short printable string")

    text = record.get("text")
    if not isinstance(text, str) or not text:
        raise ProtocolError(ERR_INVALID_REQUEST, "text must be a non-empty string")
    if len(text.encode("utf-8")) > MAX_TEXT_BYTES:
        raise ProtocolError(
            ERR_INVALID_REQUEST, f"text exceeds the {MAX_TEXT_BYTES}-byte message cap"
        )

    if "reply_expected" in record:
        reply_expected = record["reply_expected"]
        if reply_expected is True:
            raise ProtocolError(
                ERR_REPLY_NOT_SUPPORTED,
                "reply_expected=true is refused: this build advertises delivery-only",
            )
        if reply_expected is not False:
            raise ProtocolError(ERR_INVALID_REQUEST, "reply_expected must be a boolean")

    intent = record.get("intent")
    if not isinstance(intent, str) or not intent or len(intent) > MAX_INTENT_CHARS:
        raise ProtocolError(ERR_INVALID_REQUEST, "intent must be a short non-empty string")
    # The intent is rendered on ONE labelled line of the delivered prompt, so a
    # newline or other control character must not survive validation.
    if any(char in "\r\n" or ord(char) < 0x20 or ord(char) == 0x7F for char in intent):
        raise ProtocolError(
            ERR_INVALID_REQUEST, "intent must be a single line without control characters"
        )

    claims = record.get("source_claims")
    if claims is None:
        claims = {}
    if not isinstance(claims, dict):
        raise ProtocolError(ERR_INVALID_REQUEST, "source_claims must be a JSON object")

    request_id = record.get("request_id")
    if not isinstance(request_id, str):
        raise ProtocolError(ERR_INVALID_REQUEST, "request_id must be a host-qualified string")
    parse_remote_id(request_id)

    digest = record.get("digest")
    if digest is not None and (not isinstance(digest, str) or not _DIGEST_RE.fullmatch(digest)):
        raise ProtocolError(ERR_INVALID_REQUEST, "digest must be a sha256 hex string")

    normalised = {
        "schema_version": SCHEMA_VERSION,
        "dest_project": project,
        "dest_provider": provider,
        "text": text,
        "intent": intent,
        "reply_expected": False,
        "source_claims": dict(claims),
        "request_id": request_id,
    }
    if session is not None:
        normalised["dest_session"] = session
    if digest is not None:
        normalised["digest"] = digest
    return normalised


def build_request_record(
    *,
    dest_project: str,
    dest_provider: str,
    intent: str,
    text: str,
    request_id: str,
    source_claims: dict | None = None,
    dest_session: str | None = None,
    reply_expected: bool = False,
) -> dict:
    """Build and validate a ``submit`` record, with its digest.

    ``reply_expected=False`` builds the unchanged M1 schema v1 record;
    ``reply_expected=True`` builds schema v2. The digest covers
    ``schema_version`` and ``reply_expected``, so the two can never share a
    digest for the same payload.
    """
    record = {
        "schema_version": SCHEMA_VERSION_REPLY if reply_expected is True else SCHEMA_VERSION,
        "dest_project": dest_project,
        "dest_provider": dest_provider,
        "text": text,
        "intent": intent,
        "reply_expected": reply_expected,
        # Passed through as given: validate_request_record refuses a non-object.
        "source_claims": source_claims if source_claims is not None else {},
        "request_id": request_id,
    }
    if dest_session is not None:
        record["dest_session"] = dest_session
    normalised = validate_request_record(record)
    normalised["digest"] = compute_digest(normalised)
    return normalised


